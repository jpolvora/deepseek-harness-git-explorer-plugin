/**
 * Generate the local type-only mirror of `@deepseek-ai/dsh-typert-protocol`.
 *
 * Why this exists: the Typert analyzer recognizes a Remote contract only when the
 * protocol symbols it uses (`Remote`, `RemoteScope`, `TypertRemoteService`,
 * `bindTypertRemote`) are declared inside a package that is a *registered workspace
 * project* of the analyzed root — the shipped monorepo satisfies that by having the
 * protocol as `packages/typert/protocol`. An out-of-tree plugin resolves the
 * protocol from `node_modules`, which is never a registration, so generation would
 * report "publishes Remote artifacts but has no Remote methods".
 *
 * The mirror is declarations only, is never imported at runtime (the built host
 * bundle keeps importing the real npm package), and is regenerated from the
 * installed package on every host build so it cannot drift. Its internal `./x.ts`
 * specifiers are rewritten to `./x.js`, because the mirror ships no `.ts` sources.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = resolve(here, '..')
const repoRoot = resolve(packageRoot, '../..')
const source = join(packageRoot, 'node_modules', '@deepseek-ai', 'dsh-typert-protocol')
const target = join(repoRoot, 'packages', 'typert-protocol')

if (!existsSync(join(source, 'package.json'))) {
  console.error(`vendor-typert-protocol: ${source} is not installed; run pnpm install first`)
  process.exit(1)
}

const installed = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'))
const cordisVersion = JSON.parse(
  readFileSync(join(packageRoot, 'node_modules', '@deepseek-ai', 'cordis', 'package.json'), 'utf8'),
).version

rmSync(join(target, 'lib'), { recursive: true, force: true })
rmSync(join(target, 'src'), { recursive: true, force: true })
mkdirSync(join(target, 'lib', 'types'), { recursive: true })
mkdirSync(join(target, 'src'), { recursive: true })

/**
 * Copy declaration files into both faces of the mirror:
 *  - `lib/types/**\/*.d.ts` — the published layout its `exports.types` names;
 *  - `src/**\/*.ts` — the same declarations under the source layout the analyzer
 *    derives from `exports` before it looks a module symbol up in its program.
 * Internal `./x.ts` specifiers become `./x.js` because the mirror ships no `.ts`
 * sources of the original kind.
 */
function copyDeclarations(from, toLib, toSrc) {
  for (const entry of readdirSync(from, { withFileTypes: true })) {
    const sourcePath = join(from, entry.name)
    if (entry.isDirectory()) {
      copyDeclarations(sourcePath, join(toLib, entry.name), join(toSrc, entry.name))
      continue
    }
    if (!entry.name.endsWith('.d.ts')) continue
    const text = readFileSync(sourcePath, 'utf8').replace(
      /(from\s+['"])(\.{1,2}\/[^'"]+)\.ts(['"])/g,
      '$1$2.js$3',
    )
    mkdirSync(toLib, { recursive: true })
    mkdirSync(toSrc, { recursive: true })
    writeFileSync(join(toLib, entry.name), text)
    writeFileSync(join(toSrc, `${entry.name.slice(0, -'.d.ts'.length)}.ts`), text)
  }
}

copyDeclarations(join(source, 'lib', 'types'), join(target, 'lib', 'types'), join(target, 'src'))

writeFileSync(join(target, 'package.json'), `${JSON.stringify({
  name: '@deepseek-ai/dsh-typert-protocol',
  version: installed.version,
  private: true,
  description: 'Generated type-only mirror of @deepseek-ai/dsh-typert-protocol, used solely so the Typert analyzer can register the protocol as a workspace project.',
  type: 'module',
  types: 'lib/types/index.d.ts',
  exports: {
    '.': { types: './lib/types/index.d.ts' },
    './types': { types: './lib/types/types.d.ts' },
    // The generator validates every discovered contributor's Typert exports, and it
    // discovers this mirror too (the protocol's own declarations carry a surface).
    // Declaring the host artifact keeps that validation satisfied; no Remote export
    // is declared because a declarations-only package has no Remote methods.
    './typert': { types: './lib/typert.host.d.ts', default: './lib/typert.host.js' },
    './package.json': './package.json',
  },
  files: [
    'lib/types',
    'lib/typert.host.js',
    'lib/typert.host.d.ts',
    'src',
  ],
  dependencies: {
    '@deepseek-ai/cordis': `~${cordisVersion}`,
    '@deepseek-ai/dsh-brand': installed.version,
  },
}, null, 2)}\n`)

writeFileSync(join(target, 'tsconfig.json'), `${JSON.stringify({
  extends: '../../tsconfig.base.json',
  compilerOptions: { noEmit: true, declaration: false, sourceMap: false },
  include: ['src/**/*.ts', 'lib/types/**/*.d.ts'],
}, null, 2)}\n`)

writeFileSync(join(target, 'README.md'), `# @deepseek-ai/dsh-typert-protocol (generated mirror)

Generated by \`packages/git-explorer/scripts/vendor-typert-protocol.mjs\` from the installed
\`@deepseek-ai/dsh-typert-protocol@${installed.version}\`. Do not edit by hand.

The Typert analyzer only recognizes Remote contracts whose protocol symbols are declared
inside a registered workspace project, so this declarations-only mirror is registered at the
repository root for generation. Nothing imports it at runtime.
`)

const generated = readdirSync(join(target, 'lib', 'types')).length
console.log(`vendor-typert-protocol: mirrored v${installed.version} (${String(generated)} entries) into packages/typert-protocol`)
